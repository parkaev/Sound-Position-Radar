    private static void AddTitle(StackPanel stack, string text)
    {
        var tb = new TextBlock
        {
            Text = text,
            FontSize = 14.5,
            FontWeight = FontWeights.SemiBold,
            Margin = new Thickness(0, 16, 0, 4),
        };
        tb.SetResourceReference(TextBlock.ForegroundProperty, "Brush.Text");
        stack.Children.Add(tb);
    }

    private static void AddItem(StackPanel stack, string title, string text)
    {
        var tbTitle = new TextBlock
        {
            Text = title,
            FontWeight = FontWeights.SemiBold,
            Margin = new Thickness(0, 6, 0, 2),
        };
        tbTitle.SetResourceReference(TextBlock.ForegroundProperty, "Brush.Text");

        var tbBody = new TextBlock
        {
            Text = text,
            TextWrapping = TextWrapping.Wrap,
            Margin = new Thickness(0, 0, 10, 4),
        };
        tbBody.SetResourceReference(TextBlock.ForegroundProperty, "Brush.Text");

        stack.Children.Add(tbTitle);
        stack.Children.Add(tbBody);
    }
